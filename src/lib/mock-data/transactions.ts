const today = new Date();
const formatDate = (daysAgo: number, hours = 10, minutes = 0) => {
  const d = new Date(today);
  d.setDate(d.getDate() - daysAgo);
  d.setHours(hours, minutes, 0, 0);
  return d.toISOString();
};

